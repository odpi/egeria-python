"""
Generate md_processing/md_processing_utils/element_status_fields.py from Egeria's
Java source: for every open-metadata Properties class, which of the element
status properties (contentStatus, activityStatus, deploymentStatus) it has,
directly or through its superclasses.

Egeria removed `initialStatus` from new-element requests (2025-12-15,
deb8d14dc0); each type now carries its own kind of status, or none (ISSUE-113).
Re-run this when Egeria's type model changes:

    python scripts/gen_element_status_fields.py [--egeria ~/localGit/egeria-v6/egeria]
"""
import argparse
import glob
import os
import re
import subprocess

STATUS_FIELDS = ("contentStatus", "activityStatus", "deploymentStatus")
OUT = os.path.join(os.path.dirname(__file__), "..", "md_processing", "md_processing_utils",
                   "element_status_fields.py")


def scan(egeria_root: str) -> tuple[dict, dict]:
    parent, declares = {}, {}
    pattern = os.path.join(egeria_root, "open-metadata-implementation", "frameworks",
                           "**", "src", "main", "java", "**", "*Properties.java")
    for path in glob.glob(pattern, recursive=True):
        src = open(path, encoding="utf-8", errors="ignore").read()
        m = re.search(r"public\s+(?:abstract\s+)?class\s+(\w+)\s+extends\s+(\w+)", src)
        if not m:
            continue
        cls = m.group(1)
        parent[cls] = m.group(2)
        declares[cls] = {f for f in STATUS_FIELDS
                         if re.search(rf"(private|protected)\s+[\w<>]+\s+{f}\b", src)}
    return parent, declares


def fields_for(cls: str, parent: dict, declares: dict) -> list[str]:
    found, seen = set(), set()
    while cls and cls not in seen:
        seen.add(cls)
        found |= declares.get(cls, set())
        cls = parent.get(cls)
    return [f for f in STATUS_FIELDS if f in found]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--egeria", default=os.path.expanduser("~/localGit/egeria-v6/egeria"))
    args = ap.parse_args()
    parent, declares = scan(args.egeria)
    table = {c: fields_for(c, parent, declares) for c in sorted(parent)}
    head = subprocess.run(["git", "-C", args.egeria, "log", "-1", "--format=%h %cs"],
                          capture_output=True, text=True).stdout.strip() or "unknown"
    lines = [
        "# SPDX-License-Identifier: Apache-2.0",
        "# Copyright Contributors to the ODPi Egeria project.",
        '"""',
        "Status properties each Egeria Properties class has (ISSUE-113).",
        "",
        "GENERATED by scripts/gen_element_status_fields.py from Egeria source at",
        f"{head} -- do not edit by hand; re-run the script instead. A class with",
        "no status property (actors, plain assets, comments, ...) maps to ().",
        '"""',
        "",
        "STATUS_FIELDS_BY_PROPERTIES_CLASS: dict[str, tuple[str, ...]] = {",
    ]
    lines += [f"    {c!r}: ({''.join(repr(x) + ', ' for x in f).rstrip()})," for c, f in table.items()]
    lines += ["}", ""]
    with open(OUT, "w") as out:
        out.write("\n".join(lines))
    print(f"wrote {len(table)} classes ({sum(1 for f in table.values() if f)} with a status) to {os.path.normpath(OUT)} (Egeria {head})")


if __name__ == "__main__":
    main()
